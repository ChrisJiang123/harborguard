"""C1 synthetic sonar dataset generator. Each image has 1-4 targets, with 10% background-only
negatives. Class shares are uuv30/fish_school30/debris20/marine_mammal20 with global quotas. Random
range50-300m, noise0.1-0.6, target distance10%-95% and bearings across the FOV. Split85/15 into YOLO
images/labels and sonar.yaml. Dataset files are ignored; paths stay repository-relative. Example:
python -m ml.sonar.gen_dataset --n 100 --seed 0.
"""


from __future__ import annotations

import argparse
import os
from pathlib import Path

import cv2
import numpy as np

from ml.sonar.render import CLASS_NAMES, render_ping

REPO_ROOT = Path(__file__).resolve().parents[2]
CLASS_WEIGHTS = (0.30, 0.30, 0.20, 0.20)  # Same order as CLASS_NAMES.
NEG_PROB = 0.10  # Background-only negative fraction.


def _target_params(
    rng: np.random.Generator, cls: str, max_range_m: float, fov_deg: float
) -> dict:
    """Sample a target using the C1 taskbook size ranges."""
    if cls == "uuv":
        length = float(rng.uniform(2.0, 6.0))
        width = length * float(rng.uniform(0.35, 0.55))
    elif cls == "debris":
        length = float(rng.uniform(6.0, 12.0))
        width = length * float(rng.uniform(0.30, 0.45))
    elif cls == "marine_mammal":
        length = float(rng.uniform(2.0, 5.0))
        width = length * float(rng.uniform(0.25, 0.40))
    else:  # Fish diameter is a placeholder; renderer samples an actual5-30m school radius.
        length = width = 2.0 * float(rng.uniform(5.0, 30.0))
    return {
        "cls": cls,
        "range_m": float(rng.uniform(0.10, 0.95)) * max_range_m,
        "bearing_deg": float(rng.uniform(-fov_deg / 2.0, fov_deg / 2.0)),
        "length_m": length,
        "width_m": width,
        "aspect_deg": float(rng.uniform(-180.0, 180.0)),
    }


def _write_yaml(yaml_path: Path, dataset_dir: Path) -> None:
    """Write an Ultralytics dataset YAML with repository-relative paths only."""
    rel = os.path.relpath(dataset_dir.resolve(), REPO_ROOT).replace(os.sep, "/")
    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(CLASS_NAMES))
    yaml_path.parent.mkdir(parents=True, exist_ok=True)
    yaml_path.write_text(
        "# Generated by ml/sonar/gen_dataset.py (overwritten on regeneration)\n"
        f"# path is repository-relative: run training from the root, or set Ultralytics datasets_dir to it\n"
        f"path: {rel}\n"
        "train: images/train\n"
        "val: images/val\n"
        "names:\n"
        f"{names}\n",
        encoding="utf-8",
    )


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Generate a synthetic sonar YOLO dataset (C1)")
    p.add_argument("--n", type=int, default=4000, help="Image count (taskbook:4000; smoke run:100)")
    p.add_argument("--out", default="ml/datasets/sonar", help="Output directory (ignored by Git)")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--size", type=int, default=640)
    p.add_argument("--fov", type=float, default=120.0)
    p.add_argument("--yaml", default="ml/yolo/sonar.yaml", help="Output dataset YAML path")
    args = p.parse_args(argv)
    if args.n < 1:
        p.error("--n must be >=1")

    out = Path(args.out)
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        (out / sub).mkdir(parents=True, exist_ok=True)

    # Remove prior-run leftovers so changed sizes/splits do not contaminate the dataset.
    removed = 0
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        for f in (out / sub).iterdir():
            if f.is_file() and f.suffix in (".png", ".txt"):
                f.unlink()
                removed += 1
    if removed:
        print(f"Removed {removed} old output files")

    # Choose negative/1-4-target counts, then allocate classes by global quotas.
    counts_rng = np.random.default_rng([args.seed, 1])
    n_targets = [
        0 if counts_rng.random() < NEG_PROB else int(counts_rng.integers(1, 5))
        for _ in range(args.n)
    ]
    total = sum(n_targets)
    quotas = [int(round(total * w)) for w in CLASS_WEIGHTS]
    quotas[0] = total - sum(quotas[1:])  # Assign remainder to uuv to retain the exact total.
    class_seq = np.concatenate([np.full(q, i, dtype=np.int8) for i, q in enumerate(quotas)])
    np.random.default_rng([args.seed, 2]).shuffle(class_seq)
    class_iter = iter(class_seq.tolist())

    # Fixed-seed85/15 index split independent of image content.
    n_val = max(1, int(round(args.n * 0.15)))
    val_ids = set(np.random.default_rng([args.seed, 3]).permutation(args.n)[:n_val].tolist())

    stats = dict.fromkeys(CLASS_NAMES, 0)
    generated = dict.fromkeys(CLASS_NAMES, 0)   # Generated object count, including subthreshold discarded labels.
    areas = {name: [] for name in CLASS_NAMES}  # Labeled bbox area in square pixels.
    negatives = 0
    empty_labels = 0
    for i in range(args.n):
        img_rng = np.random.default_rng([args.seed, 1000 + i])
        max_range_m = float(img_rng.uniform(50.0, 300.0))
        noise = float(img_rng.uniform(0.1, 0.6))
        targets = [
            _target_params(img_rng, CLASS_NAMES[next(class_iter)], max_range_m, args.fov)
            for _ in range(n_targets[i])
        ]
        # Seed renderer speckle/patches/fish scatter for complete reproducibility.
        img, annos = render_ping(
            targets,
            max_range_m=max_range_m,
            fov_deg=args.fov,
            noise=noise,
            seed=args.seed * 1_000_003 + i,
            size=args.size,
        )

        split = "val" if i in val_ids else "train"
        cv2.imwrite(str(out / "images" / split / f"{i:06d}.png"), img)

        lines = []
        for t in targets:
            generated[t["cls"]] += 1
        for a in annos:  # YOLO-normalized center/width/height, clipped to [0,1].
            x1, y1, x2, y2 = a["bbox"]
            areas[a["cls"]].append((x2 - x1) * (y2 - y1))
            cx = min(max((x1 + x2) / 2 / args.size, 0.0), 1.0)
            cy = min(max((y1 + y2) / 2 / args.size, 0.0), 1.0)
            w = min(max((x2 - x1) / args.size, 0.0), 1.0)
            h = min(max((y2 - y1) / args.size, 0.0), 1.0)
            lines.append(f"{CLASS_NAMES.index(a['cls'])} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}")
            stats[a["cls"]] += 1
        (out / "labels" / split / f"{i:06d}.txt").write_text(
            "\n".join(lines) + ("\n" if lines else ""), encoding="utf-8"
        )
        negatives += int(not targets)
        empty_labels += int(not lines)

    _write_yaml(Path(args.yaml), out)

    # Count table: class-share deviation must stay below3 percentage points.
    print(f"Dataset: {out}; {args.n} images (train {args.n - n_val} / val {n_val}), size={args.size}")
    print(f"Background negatives: {negatives} ({negatives / args.n:.1%}, target {NEG_PROB:.0%}); empty labels: {empty_labels}")
    print(f"{'Class':<14}{'Count':>6}{'Share':>9}{'Target':>7}{'Delta':>9}")
    for name, w in zip(CLASS_NAMES, CLASS_WEIGHTS):
        share = stats[name] / total if total else 0.0
        print(f"{name:<14}{stats[name]:>6d}{share:>9.1%}{w:>7.0%}{(share - w) * 100:>+8.1f}pp")
    n_annotated = sum(stats.values())
    print(f"Generated objects {total}, labeled {n_annotated} (remaining boxes below16px² excluded by contract)")

    # Pixel-size statistics and retained small targets; reference area<64px² (~8x8).
    print("Object pixel sizes (bbox area px²):")
    print(f"{'Class':<14}{'Created':>6}{'Labeled':>8}{'Dropped':>6}{'Median':>8}{'p10':>8}{'p90':>8}{'<64px²':>8}")
    all_areas: list[float] = []
    dropped_total = 0
    for name in CLASS_NAMES:
        g, k = generated[name], stats[name]
        dropped_total += g - k
        a = np.array(areas[name]) if areas[name] else np.array([0.0])
        all_areas.extend(areas[name])
        print(f"{name:<14}{g:>6d}{k:>8d}{g - k:>6d}"
              f"{np.median(a):>8.0f}{np.percentile(a, 10):>8.0f}{np.percentile(a, 90):>8.0f}"
              f"{float((a < 64).mean()) if len(areas[name]) else 0.0:>7.0%}")
    if all_areas:
        aa = np.array(all_areas)
        n_small = int((aa < 64).sum())
        print(
            f"Small-object policy: area<64px², {n_small} objects"
            f" ({n_small / len(aa):.0%}), all retained in images; "
            f"contract area<16px² excluded {dropped_total} boxes (fraction of generated objects "
            f"{dropped_total / max(total, 1):.0%}); no extra distant-small-object removal"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
