const assert = require('node:assert/strict')
const { writeFileSync } = require('node:fs')
const path = require('node:path')
writeFileSync(path.join(__dirname, '../work/verify-a4/package.json'), '{"type":"commonjs"}\n')
const root = path.join(__dirname, '../work/verify-a4')
const { worldPosition, zoneRings, zoneCenter, zoneExtent, sceneBounds, cameraPreset, seabedElevation, smoothFlight, pingEnvelope, createTrackMotion, sampleTrackMotion, FLIGHT_SECONDS } = require(path.join(root, 'view3d/coordinates.js'))
const { parseBathymetry } = require(path.join(root, 'data/bathymetry.js'))
const { parseShoreTerrain, sampleShoreElevation } = require(path.join(root, 'data/shoreTerrain.js'))
const { parseLocalBase } = require(path.join(root, 'data/localBase.js'))
const { updateLine } = require(path.join(root, 'view3d/lineBuffers.js'))
const { buildBathymetryContours } = require(path.join(root, 'view3d/seabedContours.js'))
const { buildWaterSurfaceData } = require(path.join(root, 'view3d/waterMask.js'))
const { DEMO_ASSETS, DEMO_BUOYS, DEMO_ZONES } = require(path.join(root, 'data/demoGeometry.js'))
const { createMockEngine } = require(path.join(root, 'data/mock.js'))
const { useHarbor, receiveMessage } = require(path.join(root, 'store/useHarbor.js'))
const { toLocal, ORIGIN } = require(path.join(root, 'map2d/geo.js'))
const { VZ, SEABED_DEPTH_M } = require(path.join(root, 'theme.js'))
const near = (actual, expected, epsilon = 1e-6) => assert.ok(Math.abs(actual - expected) < epsilon, `${actual} != ${expected}`)
const nearPoint = (actual, expected) => actual.forEach((value, i) => near(value, expected[i]))

async function main() {
const { LineGeometry, LineMaterial, Line2 } = await import('three-stdlib')
nearPoint(worldPosition(ORIGIN.lat, ORIGIN.lon, 12), [0, -12, 0])
nearPoint(worldPosition(ORIGIN.lat, ORIGIN.lon, 12, 4), [0, -48, 0])
assert.equal(VZ, 1)
const asset = DEMO_ASSETS[0], buoy = DEMO_BUOYS[0]
const a2 = toLocal(asset.lat, asset.lon), b2 = toLocal(buoy.lat, buoy.lon)
const a3 = worldPosition(asset.lat, asset.lon), b3 = worldPosition(buoy.lat, buoy.lon)
near(a3[0] - b3[0], a2[0] - b2[0])
near(a3[2] - b3[2], -(a2[1] - b2[1]))
near(Math.hypot(a3[0] - b3[0], a3[2] - b3[2]), Math.hypot(a2[0] - b2[0], a2[1] - b2[1]))
const rings = zoneRings(DEMO_ZONES.features[0])
assert.equal(rings.length, 1)
assert.deepEqual(rings[0][0], rings[0].at(-1))
assert.equal(rings[0][0][1], 2)
const firstZoneCenter = zoneCenter(DEMO_ZONES.features[0], 5)
assert.equal(firstZoneCenter[1], 5)
assert.ok(Number.isFinite(firstZoneCenter[0]) && Number.isFinite(firstZoneCenter[2]))
assert.ok(zoneExtent(DEMO_ZONES.features[0]).width > 0)
assert.ok(zoneExtent(DEMO_ZONES.features[0]).length > 0)

const resources = { zones: DEMO_ZONES, assets: DEMO_ASSETS, buoys: DEMO_BUOYS, sources: { zones: 'demo', assets: 'demo', buoys: 'demo' } }
const bounds = sceneBounds(resources)
assert.ok(bounds.span >= 3600)
const overview = cameraPreset('overview', bounds)
assert.ok(overview.position[1] > 0)
assert.equal(overview.target[1], -8)
const follow = cameraPreset('follow', bounds, { lat: ORIGIN.lat, lon: ORIGIN.lon, depth_m: 12 })
nearPoint(follow.target, [0, -12, 0])
assert.deepEqual(follow.position, [230, 138, 330])
assert.ok(cameraPreset('surface', bounds).position[1] > 0)
assert.ok(cameraPreset('underwater', bounds).position[1] < 0)
assert.ok(cameraPreset('underwater', bounds).position[1] > cameraPreset('underwater', bounds).target[1])
assert.equal(cameraPreset('underwater', bounds).target[1], -16)
assert.ok(Math.hypot(cameraPreset('underwater', bounds).position[0] - cameraPreset('underwater', bounds).target[0], cameraPreset('underwater', bounds).position[2] - cameraPreset('underwater', bounds).target[2]) < 200, 'underwater preset should inspect a local seabed area rather than look almost horizontally across the whole DEM')
const dock = cameraPreset('dock', bounds, undefined, asset)
near(dock.target[0], a3[0])
near(dock.target[2], a3[2])
assert.deepEqual(cameraPreset('follow', bounds), overview)
assert.equal(FLIGHT_SECONDS, 1.5)
assert.equal(smoothFlight(-1), 0)
assert.equal(smoothFlight(.5), .5)
assert.equal(smoothFlight(1.5 / FLIGHT_SECONDS), 1)
assert.equal(smoothFlight(2), 1)

for (let x = -4000; x <= 4000; x += 200) for (let z = -4000; z <= 4000; z += 200) {
  const elevation = seabedElevation(x, z)
  assert.ok(elevation >= (-SEABED_DEPTH_M - 2) * VZ - 1e-6)
  assert.ok(elevation <= (-SEABED_DEPTH_M + 2) * VZ + 1e-6)
}
const dem = parseBathymetry(JSON.parse(require('node:fs').readFileSync(path.join(__dirname, '../public/data/seabed-dem.json'), 'utf8')))
assert.ok(dem)
assert.equal(dem.metadata.source_kind, 'regional_dem')
assert.equal(dem.metadata.horizontal_crs, 'EPSG:4269')
assert.match(dem.metadata.source, /NOAA\/NCEI/)
assert.match(dem.metadata.vertical_datum, /Mean Sea Level/)
assert.equal(dem.metadata.depth_positive, 'down')
assert.equal(dem.metadata.reference_water_level_m, 0)
assert.equal(dem.values.length, dem.metadata.width * dem.metadata.height)
assert.ok(dem.metadata.min_depth_m < dem.metadata.max_depth_m)
assert.ok(dem.metadata.nodata_cells > 0)
assert.ok(dem.values.some(value => value === dem.metadata.nodata_value))
assert.ok(dem.values.some(value => value > 0 && value !== dem.metadata.nodata_value))
const shoreTerrain = parseShoreTerrain(JSON.parse(require('node:fs').readFileSync(path.join(__dirname, '../public/data/shore-dem-usgs-3dep.json'), 'utf8')))
assert.ok(shoreTerrain)
assert.equal(shoreTerrain.metadata.vertical_datum, 'NAVD88')
assert.equal(shoreTerrain.metadata.vertical_units, 'm')
assert.equal(shoreTerrain.metadata.elevation_positive, 'up')
assert.ok(shoreTerrain.values.filter(value => value !== shoreTerrain.metadata.nodata_value).length > 60000)
assert.ok(shoreTerrain.metadata.max_elevation_m - shoreTerrain.metadata.min_elevation_m > 50, 'shoreline DEM should have actual elevation relief')
assert.ok(shoreTerrain.metadata.vertical_alignment.includes('zero offset'))
assert.match(shoreTerrain.metadata.imagery_source, /NAIP/)
const orthoPng = require('node:fs').readFileSync(path.join(__dirname, '../public/data/shore-ortho-usgs-naip.png'))
assert.deepEqual([...orthoPng.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10])
assert.equal(orthoPng.readUInt32BE(16), 1536)
assert.equal(orthoPng.readUInt32BE(20), 834)
const waterGrid = { metadata: { width: 2, height: 2, bounds: { west: -118.27, south: 33.72, east: -118.26, north: 33.73 }, nodata_value: -9999 }, values: [10, 11, 12, 13] }
const waterMesh = buildWaterSurfaceData(waterGrid)
assert.deepEqual(waterMesh.indices, [0, 2, 1, 1, 2, 3])
nearPoint(waterMesh.positions.slice(0, 3), worldPosition(33.73, -118.27, 0))
const coastlineMesh = buildWaterSurfaceData({ ...waterGrid, values: [10, -9999, 12, 13] })
assert.equal(coastlineMesh.indices.length, 0, 'water triangles must not cross land/NoData corners')
const noaaWaterMesh = buildWaterSurfaceData(dem)
assert.ok(noaaWaterMesh.indices.length > 0)
assert.equal(noaaWaterMesh.positions.length, dem.values.length * 3)
assert.ok(noaaWaterMesh.indices.every(index => dem.values[index] !== dem.metadata.nodata_value))
const contours = buildBathymetryContours(dem)
assert.ok(contours.length > 0)
assert.ok(contours.every(segment => Number.isFinite(segment.from.lat) && Number.isFinite(segment.from.lon) && Number.isFinite(segment.to.lat) && Number.isFinite(segment.to.lon)))
assert.ok(contours.every(segment => Math.abs(segment.depth / 5 - Math.round(segment.depth / 5)) < 1e-6))
assert.deepEqual(buildBathymetryContours(dem, 0), [])
const countyBuildings = parseLocalBase(JSON.parse(require('node:fs').readFileSync(path.join(__dirname, '../public/data/lacounty-port-buildings.geojson'), 'utf8')))
const realBuildings = countyBuildings.features.filter(feature => feature.properties.kind === 'building')
assert.ok(realBuildings.length > 0 && realBuildings.length <= 2000)
assert.ok(realBuildings.every(feature => feature.geometry.type === 'Polygon' && feature.properties.height_m > 0 && feature.properties.height_source === 'la-county-lariac-height'))
const firstGroundedBuilding = realBuildings.find(feature => sampleShoreElevation(shoreTerrain, feature.geometry.coordinates[0][0][1], feature.geometry.coordinates[0][0][0]) !== null)
assert.ok(firstGroundedBuilding, 'county building footprints should locate on valid shoreline DEM samples')
const buildingAnchor = firstGroundedBuilding.geometry.coordinates[0][0]
assert.ok(Number.isFinite(sampleShoreElevation(shoreTerrain, buildingAnchor[1], buildingAnchor[0])))
for (const feature of realBuildings) for (const ring of feature.geometry.coordinates) for (const [lon, lat] of ring) {
  const point = worldPosition(lat, lon)
  assert.ok(Number.isFinite(point[0]) && Number.isFinite(point[2]))
}
const boundsWithDem = sceneBounds(resources, dem)
const demBounds = dem.metadata.bounds
const demCorners = [[demBounds.south, demBounds.west], [demBounds.south, demBounds.east], [demBounds.north, demBounds.west], [demBounds.north, demBounds.east]].map(([lat, lon]) => worldPosition(lat, lon))
for (const point of demCorners) {
  assert.ok(Math.abs(point[0] - boundsWithDem.center[0]) <= boundsWithDem.width / 2 + 1e-6)
  assert.ok(Math.abs(point[2] - boundsWithDem.center[2]) <= boundsWithDem.length / 2 + 1e-6)
}
const inconsistentDem = structuredClone(dem)
inconsistentDem.metadata.nodata_cells++
assert.equal(parseBathymetry(inconsistentDem), null)
assert.ok(pingEnvelope(0, 650).opacity > 0)
near(pingEnvelope(.75, 650).radius, 327.5)
assert.equal(pingEnvelope(1.5, 650).opacity, 0)
assert.equal(pingEnvelope(-1, 650).opacity, 0)
assert.equal(pingEnvelope(Infinity, 650).opacity, 0)

const messages = []
useHarbor.getState().reset()
const engine = createMockEngine(msg => { messages.push(msg); receiveMessage(msg) })
engine.start()
engine.advance(40)
const vesselBeforePause = useHarbor.getState().tracks.T3
assert.equal(vesselBeforePause.cls, 'vessel')
assert.ok(Number.isFinite(vesselBeforePause.heading_deg))
engine.control('pause')
engine.advance(2)
assert.equal(useHarbor.getState().tracks.T3.lat, vesselBeforePause.lat)
assert.equal(useHarbor.getState().tracks.T3.lon, vesselBeforePause.lon)
engine.control('resume')
engine.advance(2)
assert.notEqual(useHarbor.getState().tracks.T3.lon, vesselBeforePause.lon)
const track = useHarbor.getState().tracks.T1
const before = JSON.stringify(track)
const motion = createTrackMotion(track)
const buffer = motion.current
assert.equal(sampleTrackMotion(motion, track, 10), buffer)
const changed = { ...track, depth_m: track.depth_m + 4 }
const startingPoint = [...motion.current]
sampleTrackMotion(motion, changed, 10)
near(sampleTrackMotion(motion, changed, 10.1)[1], startingPoint[1] - 2)
near(sampleTrackMotion(motion, changed, 10.2)[1], -(track.depth_m + 4) * VZ)
assert.equal(JSON.stringify(track), before)
assert.equal(motion.current, buffer)

useHarbor.getState().selectTrack('T1')
useHarbor.getState().setView('3d')
engine.advance(.2)
assert.equal(useHarbor.getState().selectedTrackId, 'T1')
useHarbor.getState().setView('2d')
assert.equal(useHarbor.getState().selectedTrackId, 'T1')
useHarbor.getState().setView('3d')
engine.startScenario('a')
assert.equal(useHarbor.getState().view, '3d')
assert.equal(useHarbor.getState().selectedTrackId, null)
engine.stop()

// Exercise real Three.js/three-stdlib attribute objects without a renderer or network.
const geometry = new LineGeometry()
geometry.setPositions(new Float32Array(60 * 3))
const material = new LineMaterial()
const line = new Line2(geometry, material)
line.computeLineDistances()
const starts = geometry.getAttribute('instanceStart')
const ends = geometry.getAttribute('instanceEnd')
const backingArray = starts.data.array
updateLine(line, [[0, 0, 0], [3, 4, 0], [3, 4, 12]])
assert.equal(geometry.instanceCount, 2)
assert.equal(starts.getX(1), 3)
assert.equal(ends.getZ(1), 12)
assert.equal(geometry.getAttribute('instanceDistanceStart').getX(1), 5)
assert.equal(geometry.getAttribute('instanceDistanceEnd').getX(1), 17)
for (let i = 0; i < 1500; i++) updateLine(line, [[i, -96, i], [i + 3, -96, i + 4]])
assert.equal(geometry.getAttribute('instanceStart'), starts)
assert.equal(geometry.getAttribute('instanceEnd'), ends)
assert.equal(starts.data.array, backingArray)
assert.equal(geometry.instanceCount, 1)
updateLine(line, [])
assert.equal(geometry.instanceCount, 0)
geometry.dispose(); material.dispose()

console.log(`PASS A4: shared 2D/3D coordinates; ${realBuildings.length} LA County building footprints/heights; NOAA/NCEI bathymetry ${dem.metadata.width}x${dem.metadata.height}, NAD83/MSL; USGS 3DEP land DEM ${shoreTerrain.metadata.width}x${shoreTerrain.metadata.height}, ${shoreTerrain.metadata.nodata_cells} masked cells, ${shoreTerrain.values.length - shoreTerrain.metadata.nodata_cells} land elevations, relief ${shoreTerrain.metadata.min_elevation_m.toFixed(1)}–${shoreTerrain.metadata.max_elevation_m.toFixed(1)} m NAVD88; coastline water-mask clipping (${noaaWaterMesh.indices.length / 3} triangles); ${contours.length} bathymetry contours; view presets; replay-synchronized motion/pause/resume; reusable Three.js buffers. Target-device 1920x1080 GPU/FPS validation remains outstanding.`)
}
main().catch(error => { console.error(error); process.exitCode = 1 })
