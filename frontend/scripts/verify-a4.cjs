const assert = require('node:assert/strict')
const { writeFileSync } = require('node:fs')
const path = require('node:path')
writeFileSync(path.join(__dirname, '../work/verify-a4/package.json'), '{"type":"commonjs"}\n')
const root = path.join(__dirname, '../work/verify-a4')
const { worldPosition, zoneRings, zoneCenter, sceneBounds, cameraPreset, seabedElevation, smoothFlight, pingEnvelope, createTrackMotion, sampleTrackMotion, FLIGHT_SECONDS } = require(path.join(root, 'view3d/coordinates.js'))
const { updateLine } = require(path.join(root, 'view3d/lineBuffers.js'))
const { DEMO_ASSETS, DEMO_BUOYS, DEMO_ZONES } = require(path.join(root, 'data/demoGeometry.js'))
const { createMockEngine } = require(path.join(root, 'data/mock.js'))
const { useHarbor, receiveMessage } = require(path.join(root, 'store/useHarbor.js'))
const { toLocal, ORIGIN } = require(path.join(root, 'map2d/geo.js'))
const { VZ, SEABED_DEPTH_M } = require(path.join(root, 'theme.js'))
const near = (actual, expected, epsilon = 1e-6) => assert.ok(Math.abs(actual - expected) < epsilon, `${actual} != ${expected}`)
const nearPoint = (actual, expected) => actual.forEach((value, i) => near(value, expected[i]))

async function main() {
const { LineGeometry, LineMaterial, Line2 } = await import('three-stdlib')
nearPoint(worldPosition(ORIGIN.lat, ORIGIN.lon, 12), [0, -96, 0])
assert.equal(VZ, 8)
const asset = DEMO_ASSETS[0], buoy = DEMO_BUOYS[0]
const a2 = toLocal(asset.lat, asset.lon), b2 = toLocal(buoy.lat, buoy.lon)
const a3 = worldPosition(asset.lat, asset.lon), b3 = worldPosition(buoy.lat, buoy.lon)
near(a3[0] - b3[0], a2[0] - b2[0])
near(a3[2] - b3[2], -(a2[1] - b2[1]))
near(Math.hypot(a3[0] - b3[0], a3[2] - b3[2]), Math.hypot(a2[0] - b2[0], a2[1] - b2[1]))
const rings = zoneRings(DEMO_ZONES.features[0])
assert.equal(rings.length, 1)
assert.deepEqual(rings[0][0], rings[0].at(-1))
assert.equal(rings[0][0][1], 2)
const firstZoneCenter = zoneCenter(DEMO_ZONES.features[0], 5)
assert.equal(firstZoneCenter[1], 5)
assert.ok(Number.isFinite(firstZoneCenter[0]) && Number.isFinite(firstZoneCenter[2]))

const resources = { zones: DEMO_ZONES, assets: DEMO_ASSETS, buoys: DEMO_BUOYS, sources: { zones: 'demo', assets: 'demo', buoys: 'demo' } }
const bounds = sceneBounds(resources)
assert.ok(bounds.span >= 3600)
const overview = cameraPreset('overview', bounds)
assert.ok(overview.position[1] > 0)
assert.deepEqual(overview.target, bounds.center)
const follow = cameraPreset('follow', bounds, { lat: ORIGIN.lat, lon: ORIGIN.lon, depth_m: 12 })
nearPoint(follow.target, [0, -96, 0])
assert.deepEqual(follow.position, [230, 54, 330])
const dock = cameraPreset('dock', bounds, undefined, asset)
near(dock.target[0], a3[0])
near(dock.target[2], a3[2])
assert.deepEqual(cameraPreset('follow', bounds), overview)
assert.equal(FLIGHT_SECONDS, 1.5)
assert.equal(smoothFlight(-1), 0)
assert.equal(smoothFlight(.5), .5)
assert.equal(smoothFlight(1.5 / FLIGHT_SECONDS), 1)
assert.equal(smoothFlight(2), 1)

for (let x = -4000; x <= 4000; x += 200) for (let z = -4000; z <= 4000; z += 200) {
  const elevation = seabedElevation(x, z)
  assert.ok(elevation >= (-SEABED_DEPTH_M - 2) * VZ - 1e-6)
  assert.ok(elevation <= (-SEABED_DEPTH_M + 2) * VZ + 1e-6)
}
assert.ok(pingEnvelope(0, 650).opacity > 0)
near(pingEnvelope(.75, 650).radius, 327.5)
assert.equal(pingEnvelope(1.5, 650).opacity, 0)
assert.equal(pingEnvelope(-1, 650).opacity, 0)
assert.equal(pingEnvelope(Infinity, 650).opacity, 0)

const messages = []
useHarbor.getState().reset()
const engine = createMockEngine(msg => { messages.push(msg); receiveMessage(msg) })
engine.start()
engine.advance(40)
const vesselBeforePause = useHarbor.getState().tracks.T3
assert.equal(vesselBeforePause.cls, 'vessel')
assert.ok(Number.isFinite(vesselBeforePause.heading_deg))
engine.control('pause')
engine.advance(2)
assert.equal(useHarbor.getState().tracks.T3.lat, vesselBeforePause.lat)
assert.equal(useHarbor.getState().tracks.T3.lon, vesselBeforePause.lon)
engine.control('resume')
engine.advance(2)
assert.notEqual(useHarbor.getState().tracks.T3.lon, vesselBeforePause.lon)
const track = useHarbor.getState().tracks.T1
const before = JSON.stringify(track)
const motion = createTrackMotion(track)
const buffer = motion.current
assert.equal(sampleTrackMotion(motion, track, 10), buffer)
const changed = { ...track, depth_m: track.depth_m + 4 }
const startingPoint = [...motion.current]
sampleTrackMotion(motion, changed, 10)
near(sampleTrackMotion(motion, changed, 10.1)[1], startingPoint[1] - 16)
near(sampleTrackMotion(motion, changed, 10.2)[1], -(track.depth_m + 4) * VZ)
assert.equal(JSON.stringify(track), before)
assert.equal(motion.current, buffer)

useHarbor.getState().selectTrack('T1')
useHarbor.getState().setView('3d')
engine.advance(.2)
assert.equal(useHarbor.getState().selectedTrackId, 'T1')
useHarbor.getState().setView('2d')
assert.equal(useHarbor.getState().selectedTrackId, 'T1')
useHarbor.getState().setView('3d')
engine.startScenario('a')
assert.equal(useHarbor.getState().view, '3d')
assert.equal(useHarbor.getState().selectedTrackId, null)
engine.stop()

// Exercise real Three.js/three-stdlib attribute objects without a renderer or network.
const geometry = new LineGeometry()
geometry.setPositions(new Float32Array(60 * 3))
const material = new LineMaterial()
const line = new Line2(geometry, material)
line.computeLineDistances()
const starts = geometry.getAttribute('instanceStart')
const ends = geometry.getAttribute('instanceEnd')
const backingArray = starts.data.array
updateLine(line, [[0, 0, 0], [3, 4, 0], [3, 4, 12]])
assert.equal(geometry.instanceCount, 2)
assert.equal(starts.getX(1), 3)
assert.equal(ends.getZ(1), 12)
assert.equal(geometry.getAttribute('instanceDistanceStart').getX(1), 5)
assert.equal(geometry.getAttribute('instanceDistanceEnd').getX(1), 17)
for (let i = 0; i < 1500; i++) updateLine(line, [[i, -96, i], [i + 3, -96, i + 4]])
assert.equal(geometry.getAttribute('instanceStart'), starts)
assert.equal(geometry.getAttribute('instanceEnd'), ends)
assert.equal(starts.data.array, backingArray)
assert.equal(geometry.instanceCount, 1)
updateLine(line, [])
assert.equal(geometry.instanceCount, 0)
geometry.dispose(); material.dispose()

console.log('PASS A4: shared 2D/3D coordinates; depth x8; relative position alignment; zone/route centers; data-driven vessel position and heading with pause/resume; camera presets and 1.5s easing; seabed +/-2m; 1.5s ping envelope; in-place motion; selection/view preservation; reusable real Three.js line attributes across 1500 updates. GPU rendering/FPS still needs browser validation.')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
